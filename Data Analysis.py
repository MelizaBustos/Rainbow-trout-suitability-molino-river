# ETAPA 3: PREPARACIÓN PARA EL MODELO XGBOOST


import numpy as np
import pandas as pd

from sklearn.model_selection import LeaveOneGroupOut
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix,
    classification_report,
    roc_auc_score
)

from xgboost import XGBClassifier



# 1. Variables predictoras


features = [
    "temperatura",
    "ph",
    "oxigeno_disuelto"
]

X = df[features].copy()


# 2. Variable objetivo


y = df["aptitud"].map({
    "NO APTO": 0,
    "APTO": 1
})

# Grupos P1-P5
groups = df["punto"]



# 3. Comprobar datos


print("Dimensión de X:", X.shape)

print("\nDistribución de y:")
print(y.value_counts())

print("\nPuntos:")
print(groups.value_counts().sort_index())



# 4. Configurar Leave-One-Group-Out


logo = LeaveOneGroupOut()

resultados = []
predicciones = []


# 5. Entrenamiento y validación


for train_idx, test_idx in logo.split(X, y, groups):

    X_train = X.iloc[train_idx]
    X_test = X.iloc[test_idx]

    y_train = y.iloc[train_idx]
    y_test = y.iloc[test_idx]

    punto_prueba = groups.iloc[test_idx].iloc[0]

    print("\n" + "=" * 60)
    print("PUNTO DE PRUEBA:", punto_prueba)
    print("=" * 60)

    modelo = XGBClassifier(
        n_estimators=300,
        max_depth=5,
        learning_rate=0.05,
        subsample=0.8,
        colsample_bytree=0.8,
        objective="binary:logistic",
        eval_metric="logloss",
        random_state=42
    )

    modelo.fit(
        X_train,
        y_train
    )

    # Predicción
    y_pred = modelo.predict(X_test)

    # Probabilidad de APTO
    y_prob = modelo.predict_proba(X_test)[:, 1]



    # 6. Métricas


    accuracy = accuracy_score(
        y_test,
        y_pred
    )

    precision = precision_score(
        y_test,
        y_pred,
        zero_division=0
    )

    recall = recall_score(
        y_test,
        y_pred,
        zero_division=0
    )

    f1 = f1_score(
        y_test,
        y_pred,
        zero_division=0
    )

    # AUC solo si existen ambas clases
    if y_test.nunique() == 2:
        auc = roc_auc_score(
            y_test,
            y_prob
        )
    else:
        auc = np.nan


    resultados.append({
        "punto_prueba": punto_prueba,
        "accuracy": accuracy,
        "precision": precision,
        "recall": recall,
        "f1_score": f1,
        "roc_auc": auc
    })


    # Guardar predicciones
    pred_temp = X_test.copy()

    pred_temp["punto"] = punto_prueba

    pred_temp["real"] = y_test.values

    pred_temp["predicho"] = y_pred

    pred_temp["probabilidad_apto"] = y_prob

    predicciones.append(pred_temp)



# 7. Resultados finales


resultados_logo = pd.DataFrame(
    resultados
)

print("\nRESULTADOS POR PUNTO")
display(
    resultados_logo.round(4)
)


print("\nPROMEDIO DE MÉTRICAS")

