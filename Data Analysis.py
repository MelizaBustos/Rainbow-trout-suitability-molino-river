"""## 22. Revisión de valores extremos mediante rango intercuartílico (IQR)

Esta celda **no elimina datos**. Solo identifica cuántos valores serían considerados extremos según el criterio IQR.

"""

resumen_outliers = []

for punto in ["P1", "P2", "P3", "P4", "P5"]:
    sub = df[df["punto"] == punto]

    for variable in variables:
        q1 = sub[variable].quantile(0.25)
        q3 = sub[variable].quantile(0.75)
        iqr = q3 - q1

        limite_inferior = q1 - 1.5 * iqr
        limite_superior = q3 + 1.5 * iqr

        n_outliers = (
            (sub[variable] < limite_inferior) |
            (sub[variable] > limite_superior)
        ).sum()

        resumen_outliers.append({
            "punto": punto,
            "variable": variable,
            "limite_inferior_IQR": limite_inferior,
            "limite_superior_IQR": limite_superior,
            "n_valores_extremos": int(n_outliers),
            "porcentaje": 100 * n_outliers / len(sub)
        })

outliers_df = pd.DataFrame(resumen_outliers)

display(outliers_df.round(3))

